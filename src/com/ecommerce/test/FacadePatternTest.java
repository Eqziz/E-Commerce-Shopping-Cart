package com.ecommerce.test;

import com.ecommerce.adapter.PaymentGateway;
import com.ecommerce.adapter.StripePaymentAdapter;
import com.ecommerce.cart.ShoppingCart;
import com.ecommerce.decorator.OrderItem;
import com.ecommerce.decorator.StandardOrderItem;
import com.ecommerce.facade.CheckoutFacade;
import com.ecommerce.model.Customer;
import com.ecommerce.model.Order;
import com.ecommerce.model.OrderStatus;
import com.ecommerce.model.PhysicalProduct;
import com.ecommerce.model.ProductType;
import com.ecommerce.observer.InventorySubject;
import com.ecommerce.strategy.PercentageDiscountStrategy;

import java.util.List;

/**
 * Unit tests validating Facade pattern integration.
 * 
 * @author baktiyarovamereilim-lang
 */
public class FacadePatternTest {

    public static void runTests() {
        System.out.println("Running FacadePatternTest...");
        InventorySubject inventory = new InventorySubject();
        PaymentGateway gateway = new StripePaymentAdapter("sk_test_key");
        CheckoutFacade facade = new CheckoutFacade(inventory, gateway);

        PhysicalProduct tablet = new PhysicalProduct("TAB-1", "Pro Tablet", "11-inch Tablet", 600.0, ProductType.ELECTRONICS, 0.5, "Standard");
        inventory.registerProduct(tablet, 10);

        ShoppingCart cart = new ShoppingCart("CART-TEST", "CUST-T");
        cart.addItem(tablet, 2); // 2 units = $1200

        Customer customer = new Customer("CUST-T", "Test User", "test@user.com", "Main Street 1", "GOLD");
        PercentageDiscountStrategy promo = new PercentageDiscountStrategy("SAVE10", 10.0);
        List<OrderItem> items = List.of(new StandardOrderItem(tablet, 2));

        Order order = facade.processCheckout(cart, customer, promo, gateway, items);

        SimpleAssert.assertNotNull(order, "Order must be generated by facade");
        SimpleAssert.assertEquals(OrderStatus.PAID, order.getStatus(), "Order status must be PAID");
        SimpleAssert.assertEquals(8, inventory.getStock(tablet.getId()), "Inventory must be decremented by 2 units (10 - 2 = 8)");
        SimpleAssert.assertTrue(cart.isEmpty(), "Shopping cart must be cleared upon completed checkout");

        System.out.println("  [PASSED] FacadePatternTest passed.");
    }
}
